"""Build the artist-grouped, quadrant-stratified 10-fold file (fold-file contract).

Reads data/interim/labels.csv (output of data/audit/audit_deam.py) and writes

  splits/folds_artist.csv         song_id, artist_norm, quadrant, fold   (committed)
  splits/folds_artist_report.md   per-fold sizes, quadrant shares, settings (committed)

Rule (docs/contracts.md#fold-file):
  StratifiedGroupKFold(n_splits=10, shuffle=True, random_state=415),
  groups = artist_norm, y = quadrant of the rescaled mean (mu_V, mu_A).

Quadrant (0 counts as positive, numbered counter-clockwise from "happy"):
  1: V >= 0, A >= 0    2: V < 0, A >= 0    3: V < 0, A < 0    4: V >= 0, A < 0

Validation rule: for test fold k, fold (k + 1) % 10 is validation and the other
8 folds are training. Use `fold_roles` below instead of re-implementing it.

Usage:
  python splits/make_folds.py                      # write the file, then run the test
  python splits/make_folds.py --labels path/to/labels.csv
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
from sklearn.model_selection import StratifiedGroupKFold

ROOT = Path(__file__).resolve().parents[1]
N_SPLITS = 10
RANDOM_STATE = 415
COLUMNS = ["song_id", "artist_norm", "quadrant", "fold"]


def quadrant(mu_v: pd.Series, mu_a: pd.Series) -> pd.Series:
    """V-A quadrant 1-4 of the rescaled mean; 0 counts as positive."""
    v_pos, a_pos = mu_v >= 0, mu_a >= 0
    q = np.select([v_pos & a_pos, ~v_pos & a_pos, ~v_pos & ~a_pos], [1, 2, 3], default=4)
    return pd.Series(q, index=mu_v.index, dtype=int)


def fold_roles(fold: pd.Series | np.ndarray, k: int, n_splits: int = N_SPLITS) -> np.ndarray:
    """Role of each clip when fold k is the test fold: 'train', 'val' or 'test'.

    >>> folds = pd.read_csv("splits/folds_artist.csv")
    >>> role = fold_roles(folds["fold"], k=3)
    >>> train_ids = folds.loc[role == "train", "song_id"]
    """
    fold = np.asarray(fold)
    role = np.full(fold.shape, "train", dtype=object)
    role[fold == (k + 1) % n_splits] = "val"
    role[fold == k] = "test"
    return role


def make_folds(labels: pd.DataFrame) -> pd.DataFrame:
    df = labels[["song_id", "artist_norm", "mu_V", "mu_A"]].copy()
    df["song_id"] = df["song_id"].astype(int)
    # Shuffled StratifiedGroupKFold depends on row order: fix it.
    df = df.sort_values("song_id").reset_index(drop=True)
    df["quadrant"] = quadrant(df["mu_V"], df["mu_A"])

    sgkf = StratifiedGroupKFold(n_splits=N_SPLITS, shuffle=True, random_state=RANDOM_STATE)
    fold = np.full(len(df), -1, dtype=int)
    for k, (_, test_idx) in enumerate(sgkf.split(np.zeros(len(df)), df["quadrant"], groups=df["artist_norm"])):
        fold[test_idx] = k
    df["fold"] = fold
    return df[COLUMNS]


def report(folds: pd.DataFrame, labels_path: Path) -> str:
    q_counts = pd.crosstab(folds["fold"], folds["quadrant"])
    q_share = q_counts.div(q_counts.sum(axis=1), axis=0)
    overall = folds["quadrant"].value_counts(normalize=True).sort_index()
    artists = folds.groupby("fold")["artist_norm"].nunique()

    lines = [
        "# Fold file report: `splits/folds_artist.csv`",
        "",
        "Generated by `python splits/make_folds.py`. Do not edit by hand.",
        "",
        "## Settings",
        "",
        f"- `StratifiedGroupKFold(n_splits={N_SPLITS}, shuffle=True, random_state={RANDOM_STATE})`",
        "- groups: `artist_norm`; y: `quadrant` (1: V≥0 A≥0, 2: V<0 A≥0, 3: V<0 A<0, 4: V≥0 A<0; 0 counts as positive)",
        "- rows sorted by `song_id` before splitting",
        f"- input: `{labels_path.as_posix()}` ({len(folds)} clips, {folds['artist_norm'].nunique()} artists)",
        f"- scikit-learn {sklearn.__version__}, numpy {np.__version__}, pandas {pd.__version__}, "
        f"python {sys.version.split()[0]}",
        "- validation for test fold k: fold (k + 1) % 10",
        "",
        "## Folds",
        "",
        "| fold | clips | artists | Q1 | Q2 | Q3 | Q4 |",
        "|---|---|---|---|---|---|---|",
    ]
    for k in q_counts.index:
        shares = " | ".join(f"{q_share.loc[k, q]:.3f}" for q in (1, 2, 3, 4))
        lines.append(f"| {k} | {q_counts.loc[k].sum()} | {artists.loc[k]} | {shares} |")
    lines.append(f"| all | {len(folds)} | {folds['artist_norm'].nunique()} | "
                 + " | ".join(f"{overall.get(q, 0):.3f}" for q in (1, 2, 3, 4)) + " |")
    max_dev = (q_share - overall).abs().max().max()
    sizes = q_counts.sum(axis=1)
    lines += [
        "",
        f"- fold size: min {sizes.min()}, max {sizes.max()}",
        f"- largest deviation of a fold's quadrant share from the overall share: {max_dev:.3f}",
        "- integrity test: every clip once, no artist in two folds (see `splits/test_folds.py`)",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--labels", type=Path, default=ROOT / "data/interim/labels.csv")
    ap.add_argument("--out", type=Path, default=ROOT / "splits/folds_artist.csv")
    ap.add_argument("--report", type=Path, default=ROOT / "splits/folds_artist_report.md")
    args = ap.parse_args()

    labels = pd.read_csv(args.labels)
    folds = make_folds(labels)
    folds.to_csv(args.out, index=False, encoding="utf-8", lineterminator="\n")
    try:
        shown = args.labels.resolve().relative_to(ROOT)
    except ValueError:
        shown = Path(args.labels.name)
    args.report.write_text(report(folds, shown), encoding="utf-8", newline="\n")
    meta = {"n_splits": N_SPLITS, "random_state": RANDOM_STATE, "sklearn": sklearn.__version__}
    print(f"[write] {args.out} ({len(folds)} rows)  {json.dumps(meta)}")
    print(f"[write] {args.report}")

    from test_folds import check  # same folder
    check(folds, labels)
    print("[check] integrity test PASSED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
